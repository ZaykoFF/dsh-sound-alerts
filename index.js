/**
 * agent-sound-alerts — sound cues for three agent situations:
 *
 *  1. Task completed: the session moved from `running` to `idle` (`api-session/status`).
 *  2. Context overflow: history compaction started (`session/event`, type `compaction/start`).
 *  3. Clarifying question: `ask_user_question` was called (broadcast `session/event`,
 *     type `tool/call` / `tool/ptc-dispatch`), plus the waterfall `user-questions/request`
 *     event as a fallback (for approval/plan-review questions outside the tool).
 *     The waterfall event is CLAIMED by the first answering listener, so on its own
 *     it is unreliable — the primary trigger is the tool/call in the session log.
 *
 * Sound plays on the Host process machine: Windows — powershell.exe with
 * System.Media.SoundPlayer (by default the light drum "taps" from this package's
 * sounds/ directory: muted hits with a fast pitch drop, peak ~-12 dBFS); on
 * Windows only .wav paths play, a missing or wrong-format file falls back to
 * short quiet taps through [console]::beep (warned once per cue). macOS —
 * afplay, Linux — paplay, then aplay; there, a missing file stays silent.
 *
 * The plugin has no Config schema dependency: values are read from the patch entry
 * and validated by hand (see resolveConfig) so the package does not pull another
 * package's schemastery through the linked local package's resolve chain.
 *
 * @module @zaykoff/dsh-sound-alerts
 */
import { spawn } from 'node:child_process';
import { appendFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const name = 'agent-sound-alerts';
export const inject = ['sessions', 'timer'];

const KINDS = ['taskDone', 'cacheOverflow', 'question'];

/** The wav cue directory inside the package (generated by scripts/make_sounds.py). */
const PKG_DIR = dirname(fileURLToPath(import.meta.url));

/**
 * Light drum cues: short muted taps (a membrane tone with a fast downward pitch
 * drop plus a soft noise hit), no ringing and no sharp fronts, peak ~-12 dBFS.
 */
const DEFAULT_SOUNDS = {
	taskDone: join(PKG_DIR, 'sounds', 'task_done.wav'), // three taps bottom-up: dong-ding-ding
	cacheOverflow: join(PKG_DIR, 'sounds', 'cache_overflow.wav'), // two low muted hits
	question: join(PKG_DIR, 'sounds', 'question.wav'), // two short light ticks
};

/** Fallback taps (frequency Hz, duration ms) for when the wav is unavailable. */
const BEEP_PATTERNS = {
	taskDone: [
		[190, 80],
		[260, 70],
		[330, 70],
	], // the same three bottom-up taps
	cacheOverflow: [
		[150, 90],
		[115, 90],
	], // two low "thump-thump"
	question: [
		[340, 60],
		[430, 60],
	], // two short ticks
};

/** @param ctx {import('@deepseek-ai/cordis').Context} @param config {Record<string, unknown>} */
export function apply(ctx, config = {}) {
	const cfg = resolveConfig(config, ctx);
	/** Debug file logging (cfg.debugLogFile) — for diagnosing audio. */
	const dbgPath =
		typeof cfg.debugLogFile === 'string'
			? cfg.debugLogFile
			: cfg.debugLogFile === true
				? join(PKG_DIR, 'debug.log')
				: null;
	const dbg = dbgPath
		? (msg) => {
				try {
					appendFileSync(dbgPath, `${new Date().toISOString()} ${msg}\n`);
				} catch {
					/* debugging must never bring the plugin down */
				}
			}
		: () => {};
	ctx.logger.info(
		'agent-sound-alerts: %s (taskDone=%s, cacheOverflow=%s, question=%s, includeSubagents=%s)',
		cfg.enabled ? 'enabled' : 'disabled by config',
		String(cfg.sounds.taskDone),
		String(cfg.sounds.cacheOverflow),
		String(cfg.sounds.question),
		String(cfg.includeSubagents),
	);
	if (!cfg.enabled) return;

	/** @type {Map<string, number>} When each cue last played. */
	const lastPlayed = new Map();
	/** @type {Map<string, boolean>} Last observed running state per session. */
	const runningBySession = new Map();
	const warnedCommands = new Set();
	/** @type {Set<string>} Cues whose audio problems were already reported. */
	const warnedFormats = new Set();
	let warnedNoPlayer = false;

	const isSubagent = (session) =>
		session?.header?.origin === 'subagent' || (session?.header?.delegationDepth ?? 0) > 0;

	/** Hidden spawn without pipes; ENOENT tries the next command in the list. */
	function spawnFirst(candidates) {
		const attempt = (index) => {
			const [command, args] = candidates[index];
			let child;
			try {
				child = spawn(command, args, { stdio: 'ignore', windowsHide: true });
			} catch (error) {
				warnCommand(command, error);
				if (index + 1 < candidates.length) attempt(index + 1);
				return;
			}
			child.on('error', (error) => {
				if (error?.code === 'ENOENT' && index + 1 < candidates.length) {
					attempt(index + 1);
					return;
				}
				warnCommand(command, error);
			});
			child.unref();
		};
		attempt(0);
	}

	function warnCommand(command, error) {
		if (warnedCommands.has(command)) return;
		warnedCommands.add(command);
		ctx.logger.warn('agent-sound-alerts: failed to run "%s": %o', command, error);
	}

	function playBeeps(kind) {
		const notes = BEEP_PATTERNS[kind] ?? BEEP_PATTERNS.question;
		const script = notes
			.map(([freq, duration]) => `[console]::beep(${freq},${duration}); Start-Sleep -Milliseconds 70`)
			.join('');
		spawnFirst([
			[
				'powershell.exe',
				['-NoProfile', '-NonInteractive', '-WindowStyle', 'Hidden', '-Command', script],
			],
		]);
	}

	function emit(kind) {
		const sound = cfg.sounds[kind];
		if (sound === false) {
			dbg(`emit ${kind}: sound disabled by config`);
			return;
		}
		const platform = process.platform;
		if (platform === 'win32') {
			if (typeof sound !== 'string') {
				dbg(`emit ${kind}: non-string sound ${String(sound)} -> beeps`);
				playBeeps(kind);
				return;
			}
			if (!/\.wav$/i.test(sound)) {
				if (!warnedFormats.has(kind)) {
					warnedFormats.add(kind);
					ctx.logger.warn('agent-sound-alerts: "%s" is not a .wav; Windows plays beeps for %s', sound, kind);
				}
				dbg(`emit ${kind}: not a .wav -> beeps`);
				playBeeps(kind);
				return;
			}
			if (!existsSync(sound)) {
				if (!warnedFormats.has(kind)) {
					warnedFormats.add(kind);
					ctx.logger.warn('agent-sound-alerts: "%s" not found; using beeps for %s', sound, kind);
				}
				dbg(`emit ${kind}: missing file ${sound} -> beeps`);
				playBeeps(kind);
				return;
			}
			const quoted = sound.replace(/'/g, "''");
			dbg(`emit ${kind}: powershell SoundPlayer "${sound}"`);
			spawnFirst([
				[
					'powershell.exe',
					[
						'-NoProfile',
						'-NonInteractive',
						'-WindowStyle',
						'Hidden',
						'-Command',
						`(New-Object Media.SoundPlayer -ArgumentList '${quoted}').PlaySync()`,
					],
				],
			]);
			return;
		}
		if (typeof sound === 'string' && platform === 'darwin') {
			spawnFirst([
				['/usr/bin/afplay', [sound]],
				['afplay', [sound]],
			]);
			return;
		}
		if (typeof sound === 'string' && (platform === 'linux' || platform === 'freebsd')) {
			spawnFirst([
				['paplay', [sound]],
				['aplay', ['-q', sound]],
			]);
			return;
		}
		if (!warnedNoPlayer) {
			warnedNoPlayer = true;
			ctx.logger.warn('agent-sound-alerts: no audio player known for platform "%s"', platform);
		}
	}

	function play(kind) {
		const now = Date.now();
		const last = lastPlayed.get(kind) ?? 0;
		if (now - last < cfg.minIntervalMs) {
			dbg(`play ${kind}: throttled (${String(now - last)} ms since last)`);
			return;
		}
		lastPlayed.set(kind, now);
		dbg(`play ${kind}`);
		try {
			emit(kind);
		} catch (error) {
			ctx.logger.warn('agent-sound-alerts: %s playback failed: %o', kind, error);
		}
	}

	// 1. Task completed: the session transitions running -> idle.
	ctx.on('api-session/status', (sessionId, running) => {
		const previous = runningBySession.get(sessionId);
		runningBySession.set(sessionId, running);
		if (running || previous !== true) return; // only the running -> idle edge
		dbg(`status running->idle session=${sessionId}`);
		if (!cfg.includeSubagents && isSubagent(ctx.sessions.get(sessionId))) return;
		play('taskDone');
	});
	ctx.on('api-session/removed', (sessionId) => {
		runningBySession.delete(sessionId);
	});

	// 2. Context overflow: compaction starts (token-pressure automation, recovery
	// after CONTEXT_WINDOW_EXCEEDED, and /compact alike). The same listener catches
	// ask_user_question calls in the session log (tool/call): unlike
	// user-questions/request this is a broadcast, independent of waterfall listener
	// order, and it fires even when the UI claims the queue first.
	ctx.on('session/event', (session, event) => {
		if (!cfg.includeSubagents && isSubagent(session)) return;
		if (event?.type === 'compaction/start') {
			play('cacheOverflow');
			return;
		}
		if (event?.type === 'tool/call' && event.data?.name === 'ask_user_question') {
			play('question');
			return;
		}
		// A PTC ask_user_question call from a workflow also lands in the session log.
		if (event?.type === 'tool/ptc-dispatch' && event.data?.name === 'ask_user_question' && !event.data.isError) {
			play('question');
		}
	});

	// 3. Fallback for questions that do not go through the tool (approval/plan-review):
	// the waterfall itself. It fires only while no earlier listener claims it; the
	// duplicate with tool/call is absorbed by the play() throttle.
	ctx.on('user-questions/request', (request, next) => {
		dbg('user-questions/request listener fired');
		const agentId = request?.agent?.id;
		if (!cfg.includeSubagents && agentId && isSubagent(ctx.sessions.get(agentId))) {
			dbg('user-questions/request: subagent session, skipped');
			return next();
		}
		play('question');
		return next();
	});

	if (cfg.testOnStart) {
		// Audio check: cues play in sequence, otherwise the short taps
		// (each under 1 s) overlap and everything sounds like a mush.
		ctx.logger.info('agent-sound-alerts: testOnStart — playing %d cues in sequence', KINDS.length);
		let delay = 400;
		for (const kind of KINDS) {
			ctx.timeout(() => play(kind), delay);
			delay += cfg.testGapMs;
		}
	}
}

/** Hand-rolled config validation (the plugin has no Config schema — values come from the patch entry). */
const KNOWN_KEYS = ['enabled', 'includeSubagents', 'minIntervalMs', 'testOnStart', 'testGapMs', 'debugLogFile', 'sounds'];

function resolveConfig(raw, ctx) {
	const cfg = {
		enabled: true,
		includeSubagents: false,
		minIntervalMs: 1000,
		testOnStart: false,
		testGapMs: 2500,
		debugLogFile: false,
		sounds: { ...DEFAULT_SOUNDS },
	};
	if (typeof raw?.enabled === 'boolean') cfg.enabled = raw.enabled;
	if (typeof raw?.includeSubagents === 'boolean') cfg.includeSubagents = raw.includeSubagents;
	if (typeof raw?.testOnStart === 'boolean') cfg.testOnStart = raw.testOnStart;
	if (typeof raw?.debugLogFile === 'boolean' || typeof raw?.debugLogFile === 'string')
		cfg.debugLogFile = raw.debugLogFile;
	for (const key of ['minIntervalMs', 'testGapMs']) {
		if (raw?.[key] === undefined) continue;
		if (Number.isFinite(raw[key]) && raw[key] >= 0) cfg[key] = raw[key];
		else ctx.logger.warn('agent-sound-alerts: %s must be a non-negative number; using %d', key, cfg[key]);
	}
	for (const key of Object.keys(raw ?? {})) {
		if (!KNOWN_KEYS.includes(key)) ctx.logger.warn('agent-sound-alerts: unknown config key "%s" ignored', key);
	}
	if (raw?.sounds !== undefined) {
		if (typeof raw.sounds !== 'object' || raw.sounds === null) {
			ctx.logger.warn('agent-sound-alerts: sounds must be an object; using defaults');
		} else {
			for (const kind of KINDS) {
				if (!(kind in raw.sounds)) continue;
				const value = raw.sounds[kind];
				if (value === false || typeof value === 'string') cfg.sounds[kind] = value;
				else ctx.logger.warn('agent-sound-alerts: sounds.%s must be a wav path or false; using default', kind);
			}
			for (const key of Object.keys(raw.sounds)) {
				if (!KINDS.includes(key)) ctx.logger.warn('agent-sound-alerts: unknown sound "%s" ignored', key);
			}
		}
	}
	return cfg;
}
